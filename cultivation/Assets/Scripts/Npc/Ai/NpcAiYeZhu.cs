using UnityEngine;

/// <summary>
/// 野猪（YeZhu）—— 近战妖魔，**结构照抄白熊精**（<see cref="NpcAiBaiXiongJing"/>）。
///
/// | 招 | 动画 | 类别 | 属性 | 倍率 | 冷却 | 出手进度 |
/// |---|---|---|---|---|---|---|
/// | 普攻 | `Attack1` | 普通攻击 | **物理** | 1.0 | 2.5 秒 | **0.50** |
/// | 主动神通 | `Attack2` | 主动神通 | **物理** | 2.0 | **10 秒**（策划指定） | **0.70** |
/// | — | `Attack3` | 不用 | | | | |
///
/// ### 和白熊精一样的三个要点
///
/// 1. **按动画进度出伤**，不用网格碰撞：出伤和命中特效是**同一时刻**触发的，
///    看起来就是"獠牙顶到身上的那一下"。
/// 2. **站位按观感定，不按判定够不够得着定**。野猪没有长兵器，靠獠牙顶，
///    所以攻击距离比白熊精（2.5 米）更近，取 **2.2 米**。
/// 3. **冷却从收招开始算**：两次命中之间的实际间隔 ≈ 动画长度 + 冷却 + 后摇。
///    想让神通"两下正好隔 10 秒"，把 `神通冷却` 调到 8 左右。
///
/// ### ⚠️ 还要做的事：量一次出手进度
///
/// `普攻出手进度 0.50 / 神通出手进度 0.70` 是**先按白熊精的经验给的估值**，
/// 野猪的动画不一样，**必须在 Play 里逐帧采样重新量**：
/// 找到"獠牙最前伸"的那一帧，把它的动画比例填进来。量的方法和白熊精那份注释里写的一样。
/// （出处：`NpcAiBaiXiongJing.cs` 的类注释有完整的测量表。）
/// </summary>
public class NpcAiYeZhu : NpcAiDemon
{
    [Header("野猪 · 近战")]
    [Tooltip("普攻（Attack1）冷却（秒）")]
    public float 普攻冷却 = 2.5f;

    [Tooltip("主动神通（Attack2）冷却（秒）—— **策划定 10 秒**")]
    public float 神通冷却 = 10f;

    [Tooltip("普攻倍率")]
    public float 普攻倍率 = 1f;

    [Tooltip("主动神通倍率")]
    public float 神通倍率 = 2f;

    [Header("出手进度（估值，实测量过之后请改）")]
    [Tooltip("普攻在动画的百分之多少处【出伤 + 放命中特效】。\n" +
             "野猪是獠牙顶撞，取 0.50（**未经实测，待量**）")]
    [Range(0.05f, 0.95f)]
    public float 普攻出手进度 = 0.50f;

    [Tooltip("神通在动画的百分之多少处出伤。取 0.70（**未经实测，待量**）")]
    [Range(0.05f, 0.95f)]
    public float 神通出手进度 = 0.70f;

    [Header("命中特效")]
    [Tooltip("普攻（物理）留空 = 自动用 NpcAiBase.物理基础命中特效（FX/Hit_Physical）")]
    public string 普攻命中特效 = "";

    [Tooltip("主动神通用的【更重的】命中特效")]
    public string 重击命中特效 = "FX/Hit_Physical_Heavy";

    protected override void 取默认参数()
    {
        确保攻击方式();          // ★ 先保证三条默认招式在（Awake 没跑过时也不会静默早退）
        base.取默认参数();

        // 近战站位 = **中心距**。野猪没有长兵器，比白熊精的 2.5 米更近一档。
        索敌范围 = 14f;
        脱战范围 = 22f;
        攻击距离 = 2.2f;
        攻击间隔倍率 = 1.2f;
        转向速度 = 380f;      // 猪转身比熊灵活一点
        奔跑倍率 = 1f;

        if (攻击方式 == null || 攻击方式.Length < 2) return;

        // ---- 普攻：Attack1，物理普通攻击 ----
        var 普攻 = 攻击方式[0];
        普攻.动作名 = "Attack1";
        普攻.是施法 = false;                     // 近战，没有飞弹
        普攻.伤害属性 = DamageNature.物理;        // 策划：全是物理
        普攻.攻击类别 = AttackKind.普通攻击;
        普攻.技能倍率 = 普攻倍率;
        普攻.冷却 = 普攻冷却;
        普攻.出手进度 = 普攻出手进度;              // ← 出伤 + 特效都在这一刻
        普攻.命中特效路径 = 普攻命中特效;          // 留空 → 自动用基础物理命中特效
        清掉飞弹配置(普攻);

        // ---- 主动神通：Attack2，物理主动神通，冷却 10 秒 ----
        var 神通 = 攻击方式[1];
        神通.动作名 = "Attack2";
        神通.是施法 = false;
        神通.伤害属性 = DamageNature.物理;        // 策划：全是物理
        神通.攻击类别 = AttackKind.主动神通;
        神通.技能倍率 = 神通倍率;
        神通.冷却 = 神通冷却;
        神通.出手进度 = 神通出手进度;              // ← 出伤 + 特效都在这一刻
        神通.命中特效路径 = 重击命中特效;          // ← 高级攻击用更重的命中特效
        神通.命中特效缩放 = 1.15f;
        清掉飞弹配置(神通);

        // Attack3 不用
        攻击方式[2].动作名 = "";
    }

    /// <summary>把**飞弹专属**的配置清干净（命中特效不是飞弹专属，不能清 —— 白熊精那边踩过）</summary>
    static void 清掉飞弹配置(NpcAttackConfig 配置)
    {
        配置.子弹特效路径 = "";
        配置.闪光特效路径 = "";
    }

    // ---- ASCII 别名 ----
    public float BasicCooldown => 普攻冷却;
    public float SkillCooldown => 神通冷却;
    public float AttackReach => 攻击距离;
}
