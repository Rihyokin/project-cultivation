using UnityEngine;

/// <summary>
/// 白熊精（BaiXiongJing）—— **第一个纯近战妖魔**。
///
/// 一个类覆盖 4 个变体（`BaiXiongJing_01 ~ 04`，共用同一份 `NpcDefinition`）：
/// 它们只有模型差异，行为完全一样。
///
/// | 招 | 动画 | 类别 | 属性 | 倍率 | 冷却 | 出手进度 |
/// |---|---|---|---|---|---|---|
/// | 普攻 | `Attack1` | 普通攻击 | **物理** | 1.0 | 2.5 秒 | **0.52** |
/// | 主动神通 | `Attack2` | 主动神通 | **物理** | 2.0 | **10 秒**（策划指定） | **0.78** |
/// | — | `Attack3` | 不用 | | | | |
///
/// ### 出伤方式：**按动画进度出伤，不用网格碰撞检测**
///
/// `出手进度` 是**实测**出来的「武器砸到人身上」那一刻的动画比例。
/// 在 Play 里把两条动作逐帧采样，记「武器最远能伸到熊正前方多少米」：
///
/// | 进度 | Attack1 前伸 | Attack2 前伸 |
/// |---|---|---|
/// | 0.26 ~ 0.41 | 2.1 ~ 2.3 米 | — |
/// | **0.52** | **3.44 米 ← 峰值** | — |
/// | 0.57 ~ 0.68 | 1.2 ~ 1.5（收招） | 2.5 → −0.8（往后抡） |
/// | **0.78** | — | **4.01 米 ← 峰值** |
/// | 0.94 ~ | 2.3（收招） | 3.0（收招） |
///
/// 所以普攻取 **0.52**、神通取 **0.78**。
/// **出伤和命中特效是同一时刻触发的** —— 看起来就是"打到身上的那一下"。
/// **换模型 / 改动画之后要重新量一遍**，别照抄。
///
/// > **为什么不做「用武器网格实时判定」**（我做了一版，被否掉了）：
/// > 1. 那个判定本质上是「胸口点落在一个大 AABB 里」，而熊的武器盒有 2~4 米大
/// >    —— 等价于距离判定，不如按进度出伤可预期；
/// > 2. **特效必须跟出伤同步**。网格判定下出伤发生在"盒子刚碰到人"的那一帧，
/// >    可能早于武器视觉上砸到的那一刻，特效就会提前闪 ✗
/// > 3. 每帧烘焙顶点 + 每帧碰盒的开销也省掉了。
/// >
/// > 实测数据（武器前伸多少米）**没有浪费** —— 它正好用来定 `出手进度`。
///
/// ### 站位：中心距 2.5 米
///
/// 武器最远伸到身前 **3.44 米**（实测）。
///
/// > ⚠️ **【坑·已修】别按"判定够得着"来定站位。**
/// > 第一版我填的是 3.2（武器 3.44 + 外扩 0.2，判定确实打得到），
/// > 但用户一眼就看出来「**武器没打到玩家身上**」——
/// > 武器尖只是刚够到人，等于用极限距离打空气 ✗
/// >
/// > 现在填 **2.5 米**：武器能从玩家身上**整条扫过去**，观感才是实打实砸中。
/// > 底线是别穿模：熊胶囊半径 ~1.45 + 玩家 0.4 = 1.85 米，2.5 米安全。
///
/// **通用教训**：近战的"攻击距离"要按**观感**定（武器要明显压到目标身上），
/// 不是按"判定框够不够得着"定。
///
/// ### 冷却的真实含义
///
/// `冷却` 是**从收招（动画播完）开始算**的，所以两次命中之间的实际间隔 ≈
/// 动画长度 + 冷却 + 后摇：
///   · 普攻 Attack1：1.4 + 2.5 + 0.25 ≈ **4.15 秒一下**（实测 4.08）
///   · 神通 Attack2：1.9 + 10 + 0.25 ≈ **12.15 秒一下**（实测 12.25）
/// 想让"两次命中正好隔 10 秒"，就把 `神通冷却` 调到 8 左右。
/// </summary>
public class NpcAiBaiXiongJing : NpcAiDemon
{
    [Header("白熊精 · 近战")]
    [Tooltip("普攻（Attack1）冷却（秒）")]
    public float 普攻冷却 = 2.5f;

    [Tooltip("主动神通（Attack2）冷却（秒）—— **策划定 10 秒**")]
    public float 神通冷却 = 10f;

    [Tooltip("普攻倍率")]
    public float 普攻倍率 = 1f;

    [Tooltip("主动神通倍率")]
    public float 神通倍率 = 2f;

    [Header("出手进度（实测值，改动画后要重新量）")]
    [Tooltip("普攻在动画的百分之多少处【出伤 + 放命中特效】。\n" +
             "实测 Attack1 在 **52%** 处武器前伸最远（3.44 米），所以取 0.52。\n" +
             "出伤和特效是**同一个时刻**触发的，所以看起来就是「打中的那一下」")]
    [Range(0.05f, 0.95f)]
    public float 普攻出手进度 = 0.52f;

    [Tooltip("神通在动画的百分之多少处出伤。\n" +
             "实测 Attack2 是「先往后抡、再砸下来」，**78%** 处前伸最远（4.01 米），所以取 0.78")]
    [Range(0.05f, 0.95f)]
    public float 神通出手进度 = 0.78f;

    [Header("命中特效")]
    [Tooltip("普攻（物理）留空 = 自动用 NpcAiBase.物理基础命中特效（FX/Hit_Physical）")]
    public string 普攻命中特效 = "";

    [Tooltip("主动神通用的【更重的】命中特效（这就是策划说的「高级攻击可以用更高级的命中特效」）")]
    public string 重击命中特效 = "FX/Hit_Physical_Heavy";

    protected override void 取默认参数()
    {
        确保攻击方式();          // ★ 先保证三条默认招式在（Awake 没跑过时也不会静默早退）
        base.取默认参数();

        // 近战站位 = **中心距**。
        //
        // 【坑·已修】第一版我按"武器最远伸到 3.44 米"填了 3.2（还留了 0.4 余量）——
        // 判定确实能打到，但**观感上武器尖只是刚够到玩家**，看着像没打中 ✗
        // 现在改成 2.5 米：武器能伸 3.44 米，等于**整条武器从玩家身上扫过去**，
        // 视觉上才是实打实砸在身上。
        //
        // 底线：熊的胶囊半径 ~1.45 + 玩家 0.4 = 1.85 米，所以 2.5 米不会互相穿模。
        索敌范围 = 14f;
        脱战范围 = 22f;
        攻击距离 = 2.5f;
        攻击间隔倍率 = 1.3f;
        转向速度 = 420f;      // 熊转身慢一点才像熊，但也不能太钝
        奔跑倍率 = 1f;

        if (攻击方式 == null || 攻击方式.Length < 2) return;

        // ---- 普攻：Attack1，物理普通攻击 ----
        // 【近战出伤方式】**按动画进度出伤**，不用网格碰撞检测（见类注释里的说明）
        var 普攻 = 攻击方式[0];
        普攻.动作名 = "Attack1";
        普攻.是施法 = false;                     // 近战，没有飞弹
        普攻.伤害属性 = DamageNature.物理;        // 策划：全是物理
        普攻.攻击类别 = AttackKind.普通攻击;
        普攻.技能倍率 = 普攻倍率;
        普攻.冷却 = 普攻冷却;
        普攻.出手进度 = 普攻出手进度;              // ← 出伤 + 特效都在这一刻
        普攻.命中特效路径 = 普攻命中特效;          // 留空 → 自动用基础物理命中特效
        清掉飞弹配置(普攻);

        // ---- 主动神通：Attack2，物理主动神通，冷却 10 秒 ----
        // 【高级命中特效】普攻走默认的基础命中特效（留空即可），
        // 神通这一下更重 —— 换成重击特效 + 放大一点，读起来才分得出轻重。
        var 神通 = 攻击方式[1];
        神通.动作名 = "Attack2";
        神通.是施法 = false;
        神通.伤害属性 = DamageNature.物理;        // 策划：全是物理
        神通.攻击类别 = AttackKind.主动神通;
        神通.技能倍率 = 神通倍率;
        神通.冷却 = 神通冷却;
        神通.出手进度 = 神通出手进度;              // ← 出伤 + 特效都在这一刻
        神通.命中特效路径 = 重击命中特效;          // ← 高级攻击用更重的命中特效
        神通.命中特效缩放 = 1.15f;
        清掉飞弹配置(神通);

        // Attack3 不用
        攻击方式[2].动作名 = "";
    }

    /// <summary>
    /// 把**飞弹专属**的配置清干净。
    /// **不清的话**：哪天真填了弹道路径，这一招就会「又近战判定、又飞一颗子弹出去」。
    ///
    /// 【坑·已修】以前这里把 `命中特效路径` 也一起清了 —— 结果神通刚设好的
    /// 「重击命中特效」被自己抹掉，最后又退回基础特效（实测解析出来是 FX/Hit_Physical）✗
    /// 命中特效**不是飞弹专属**，近战也要用，不能清。
    /// </summary>
    static void 清掉飞弹配置(NpcAttackConfig 配置)
    {
        配置.子弹特效路径 = "";
        配置.闪光特效路径 = "";
    }

    // ---- ASCII 别名 ----
    public float BasicCooldown => 普攻冷却;
    public float SkillCooldown => 神通冷却;
    public float AttackReach => 攻击距离;
}
