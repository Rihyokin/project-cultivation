using UnityEngine;

/// <summary>
/// 白鹿精（BaiLuJing）—— **第一个会施放飞弹的妖魔**。
///
/// 一个类覆盖 3 个变体（靠 <c>定义.id</c> 区分，不拆三个文件）：
///
/// | 变体 | 普攻（attack1） | 主动神通（attack2） | 出生点 | 弹体 |
/// |---|---|---|---|---|
/// | 01 / 02 | 飞弹，冷却 **3s** | — | **左手骨骼末端** | 标准 |
/// | 03 | 飞弹，冷却 **3s** | 飞弹，冷却 **8s** | 普攻走左手、神通走**武器末端** | 神通**放大 1.6 倍** |
///
/// 两招都在**动画 50%** 处发射，命中造成**特殊普通攻击**伤害。
///
/// ### 飞弹的 5 个要素在这个文件里怎么落地
///
/// | 要素 | 做法 |
/// |---|---|
/// | **1 出生点** | `挂点` = `Bip01 L Finger0Nub`（左手末端）/ `Bip01 R Hand`（武器末端，带偏移） |
/// | **2 飞行路径** | **直线匀速、不追踪** —— `NpcProjectile` 起飞时锁定目标点，之后不再转向 |
/// | **3 命中效果** | `AttackSpec(特殊, 普通攻击)`，由 `NpcAiBase.在目标结算` 统一结算 + 飘字 |
/// | **4 能否被阻挡** | 用 **`Projectile_Only`（纯粒子弹道）+ 我们自己的飞行器** —— 它**不和场景碰撞**，所以墙挡不住；只检测 `拦截层`（技能神通 / 法宝 / 灵阵 放那层就能拦下） |
/// | **5 消灭点** | `最大飞行距离 = 22` 米，飞出去就**淡化消散**（不是被撞掉） |
///
/// > ⚠️ **为什么不用包里带 Rigidbody 的「实体弹丸」**：那个靠物理碰撞命中，
/// > **会被墙挡住**，和你要的"无法被场景阻挡"冲突。
/// > 要"能被场景挡"才用它（见 `飞弹制作文档.md` 的两条路线）。
///
/// ### 还差什么（等你后面做了再补）
/// - `拦截层` 现在是 **0（谁都拦不住）**。等**灵阵 / 法宝**做出来，
///   把它们放到一个层里，再把这一层填进 `攻击方式[i].拦截层` 即可 —— 飞弹会自动停下并消散
/// - **武器末端**目前只能拿右手骨骼 + 偏移近似（模型里没有武器骨骼，武器是蒙皮网格挂在根上）。
///   想精确就得让美术加一根武器末端骨骼，或者改 <see cref="取武器末端"/> 用网格包围盒的尖端
/// </summary>
public class NpcAiBaiLuJing : NpcAiDemon
{
    [Header("白鹿精 · 飞弹")]
    [Tooltip("普攻飞弹的冷却（秒）")]
    public float 普攻飞弹冷却 = 3f;

    [Tooltip("主动神通飞弹的冷却（秒）")]
    public float 神通飞弹冷却 = 8f;

    [Tooltip("发射在动画的百分之多少处（0.5 = 动画 50%）")]
    [Range(0.05f, 0.95f)]
    public float 发射进度 = 0.5f;

    [Tooltip("飞弹特效包前缀")]
    public string 包前缀 = "QFX/ProjectilesFX/VFX_Prefabs/";

    [Tooltip("纯弹道（不带飞行脚本、不带命中分支）—— 这样才能「不被场景阻挡」")]
    public string 弹道 = "Projectiles_Particles/VFX_Demon_Projectile_Only";

    [Tooltip("命中爆炸")]
    public string 命中 = "Impacts/VFX_Demon_Impact";

    [Tooltip("枪口闪光（可留空）")]
    public string 闪光 = "Flashes/VFX_Demon_Flash";

    [Tooltip("飞弹速度（米/秒）")]
    public float 飞弹速度 = 18f;

    [Tooltip("飞出这么远就自行淡化消散（消灭点，米）")]
    public float 消灭距离 = 22f;

    [Tooltip("左手末端骨骼名（普攻的出生点）")]
    public string 左手末端骨骼 = "Bip01 L Finger0Nub";

    [Tooltip("武器末端近似用的骨骼名（神通 03 的出生点）")]
    public string 武器手骨骼 = "Bip01 R Hand";

    [Tooltip("武器末端相对那只手的偏移（沿手的前方）—— 模型里没武器骨骼，只能先这么近似，要看着调")]
    public Vector3 武器末端偏移 = new Vector3(0f, 0f, 1.6f);

    [Tooltip("神通的飞弹放大多少倍（比普攻大，但别太夸张）")]
    public float 神通弹体缩放 = 1.1f;

    protected override void 取默认参数()
    {
        base.取默认参数();

        // **白鹿精是丢飞弹的，不是近战** —— 所以要站在远处打。
        // 攻击距离 = 它愿意开火的距离；飞弹自己会飞过去。
        索敌范围 = 18f;
        脱战范围 = 26f;
        攻击距离 = 12f;
        转向速度 = 900f;      // 丢飞弹的，转身要利索

        if (攻击方式 == null || 攻击方式.Length < 2) return;

        string id = 自己 != null && 自己.定义 != null ? 自己.定义.id : "";
        bool 是王 = id.EndsWith("_03");     // 白鹿精·王 才有主动神通

        // ---- 普攻飞弹（01/02/03 都有）----
        var 普攻 = 攻击方式[0];
        普攻.动作名 = "Attack1";
        普攻.是施法 = true;
        普攻.伤害属性 = DamageNature.特殊;          // 命中效果 = 特殊普通攻击
        普攻.攻击类别 = AttackKind.普通攻击;
        普攻.技能倍率 = 1f;
        普攻.出手进度 = 发射进度;
        普攻.冷却 = 普攻飞弹冷却;
        普攻.子弹速度 = 飞弹速度;
        普攻.弹体缩放 = 0.65f;      // 缩小一点：原来 1 倍太笨重
        普攻.命中特效缩放 = 1.25f;  // 但命中爆炸做足一点，打击感靠它
        普攻.最大飞行距离 = 消灭距离;
        普攻.挂点 = 左手末端骨骼;                    // 出生点 = 左手骨骼末端
        普攻.挂点偏移 = Vector3.zero;
        普攻.闪光特效路径 = 包前缀 + 闪光;
        普攻.子弹特效路径 = 包前缀 + 弹道;
        普攻.命中特效路径 = 包前缀 + 命中;

        if (!是王)
        {
            // 01/02 只有普攻：把另外两招关掉，免得它们去近战
            for (int i = 1; i < 攻击方式.Length; i++) 攻击方式[i].动作名 = "";
            return;
        }

        // ---- 主动神通 1（只有 03）----
        var 神通 = 攻击方式[1];
        神通.动作名 = "Attack2";
        神通.是施法 = true;
        神通.伤害属性 = DamageNature.特殊;
        神通.攻击类别 = AttackKind.主动神通;
        神通.技能倍率 = 2.2f;
        神通.出手进度 = 发射进度;
        神通.冷却 = 神通飞弹冷却;
        神通.子弹速度 = 飞弹速度;
        神通.弹体缩放 = 神通弹体缩放;                // 更大、特效拉足
        神通.命中特效缩放 = 1.6f;
        神通.最大飞行距离 = 消灭距离;
        神通.挂点 = 武器手骨骼;                      // 出生点 = 武器末端
        神通.挂点偏移 = 武器末端偏移;
        神通.闪光特效路径 = 包前缀 + 闪光;
        神通.子弹特效路径 = 包前缀 + 弹道;
        神通.命中特效路径 = 包前缀 + 命中;

        // 第 3 招留着不用
        攻击方式[2].动作名 = "";
    }

    /// <summary>
    /// 武器末端。模型里**没有武器骨骼**（武器 `BLJ_xx_01` 是蒙皮网格挂在根上），
    /// 所以只能拿「握武器的那只手 + 一个偏移」近似。
    /// 想精确：让美术在武器尖端加一根骨骼，然后把 <see cref="武器手骨骼"/> 换成它、偏移清零。
    /// </summary>
    public Vector3 取武器末端()
    {
        var 手 = 找挂点(武器手骨骼);
        if (手 == null) return 取出膛点();
        return 手.TransformPoint(武器末端偏移);
    }

    // ---- ASCII 别名 ----
    public float BasicShotCooldown => 普攻飞弹冷却;
    public float SkillShotCooldown => 神通飞弹冷却;
}
