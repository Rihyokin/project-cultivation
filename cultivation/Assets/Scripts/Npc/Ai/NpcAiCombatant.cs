using UnityEngine;

/// <summary>
/// 会主动打玩家的 NPC 的公共实现（妖魔 / 人类）。
///
/// 行为链：
///   好感判定（<see cref="视玩家为敌"/>）
///     → 玩家进索敌范围 → 锁定玩家、追上去
///     → 够得着 → 按 <see cref="NpcAiBase.攻击方式"/> 出手（Attack1 普攻 / Attack2·3 神通）
///     → 玩家跑出脱战范围 → 放弃、回待机
///
/// 妖魔和人类只差在「好感掉到多少才翻脸」，所以在这里做成一个字段。
/// </summary>
public abstract class NpcAiCombatant : NpcAiBase
{
    [Header("敌我判定")]
    [Tooltip("好感度 **≤ 这个值** 就视玩家为敌。\n" +
             "妖魔默认 -10（表里妖魔初始好感就是 -10 及更低）；\n" +
             "人类默认 9（= 「好感 10 及以上才友好」，策划原话是「削减到 10 以下」）")]
    public float 敌对好感阈值 = -10f;

    [Tooltip("逃跑 / 脱战后再重新索敌的冷却（秒），避免边界处反复横跳")]
    public float 重新索敌冷却 = 1.5f;

    /// <summary>是否已经锁定玩家在打（进入过战斗，直到脱战才解除）</summary>
    public bool 已交战 { get; protected set; }

    /// <summary>最近一次进入战斗的时间</summary>
    public float 上次交战时间 { get; private set; } = -999f;

    public override bool 视玩家为敌
        => 自己 != null && 自己.对主角好感度 <= 敌对好感阈值;

    // ============================================================ 敌人（战斗的唯一靶子）
    //
    // 这一层是给**战阵真灵**留的：把"敌人在哪 / 能不能开打 / 算不算脱战"抽成虚方法，
    // 真灵只覆盖这三四个点，就得到和敌对 NPC **完全同一套**战斗逻辑
    // （接近停靠距离 / 首次发现 / 每帧朝敌 / 脱战 / 出手朝向）。
    //
    // 【为什么】以前真灵是自己把「决策 / 接近 / 可出手 / 朝向」重写了一遍，
    // 于是它和怪的行为会各自跑偏（实测：侧翼格的真灵离目标 0.8 米却永远不出手）。
    // 收敛到这套虚方法之后，两边不可能再不一致。

    /// <summary>允许开打吗（默认看好感度）。战阵真灵覆盖成「只要有目标就开打」</summary>
    protected virtual bool 可以开打 => 视玩家为敌;

    /// <summary>敌人在索敌范围内吗（默认 = 玩家在索敌范围）</summary>
    protected virtual bool 敌人在索敌范围() => 玩家在索敌范围();

    /// <summary>敌人跑出脱战范围了吗（默认按「到敌人的距离」判，不是到玩家的距离）</summary>
    protected virtual bool 敌人已脱战()
    {
        if (敌人 == null || !敌人还活着) return true;
        return 到敌人距离 > Mathf.Max(脱战范围, 有效索敌范围);
    }

    /// <summary>
    /// **交战时待机播 `Fight`（战斗待机），脱战才回 `Idle`。**
    /// `Fight` 就是战斗状态的 idle，之前一直没用上。
    /// 没交战但已经敌对（刚生成、玩家还没进范围）也用 Fight —— 它本来就是"警戒"。
    /// </summary>
    protected override string 取待机动作名()
        => 可以开打 ? "Fight" : "Idle";

    /// <summary>
    /// 【坑·已修】**这里以前每帧写 `已交战 = false`。**
    ///
    /// 后果：出手完回到待机，"在战斗"这个状态就被抹掉了 → 下次出手还要重新走
    /// "首次发现"（带 <see cref="重新索敌冷却"/> 1.5 秒）→ **打一下愣半天**。
    /// 实测 16 秒里每个只出手 1~2 次，而冷却明明只有 3 秒。
    ///
    /// 正确做法：**"在战斗"只能由 `决策()` 里的"玩家已脱战"来解除**，
    /// 待机不代表脱战。所以这里只播待机动画，不动交战状态。
    /// </summary>
    protected override void 执行待机() => base.执行待机();

    /// <summary>
    /// **每帧都盯着玩家。**
    ///
    /// 以前 `朝向玩家()` 只在"进入攻击/接近"的那一下调一次，而且只在待机状态里跟 ——
    /// 结果 NPC 站在攻击距离内时**大部分时间在"攻击"状态**，压根不转；
    /// 玩家绕圈它就一直侧着身子，看着就是"转向巨慢"。
    ///
    /// 现在放在 Update 里：只要活着、玩家在索敌范围内就每帧转一次 ——
    /// 它**任何时候都是面朝玩家的**，一出手就是正的。
    /// 受击/死亡时不转（挨打还转头很怪）。
    /// </summary>
    protected override void Update()
    {
        base.Update();

        if (敌人 == null || !敌人还活着) return;
        if (状态 == NpcAiState.死亡 || 状态 == NpcAiState.受击) return;

        // ★【坑·已修】攻击动画播放期间**不转向**（见 NpcAiBase.转向 的说明）：
        // 攻击动作自带转体，这里每帧纠回目标会把转体抵消掉 → 手刺歪 ✗
        if (状态 == NpcAiState.攻击 && 攻击期间锁定朝向) return;

        // 还没发现敌人（刚生成、离得远）先不转，免得老远就开始盯人
        if (!已交战 && !敌人在索敌范围()) return;

        朝向敌人();
    }

    protected override void 决策()
    {
        if (敌人 == null || !敌人还活着) { 进入状态(NpcAiState.待机); return; }

        if (!可以开打) { 进入状态(NpcAiState.待机); return; }

        // 敌人跑远了 → 脱战
        if (敌人已脱战())
        {
            已交战 = false;
            进入状态(NpcAiState.待机);
            return;
        }

        // 还没进战斗：要敌人真的进到索敌范围里才开打
        bool 首次发现 = !已交战 && 敌人在索敌范围()
                        && Time.time - 上次交战时间 >= 重新索敌冷却;
        if (首次发现)
        {
            已交战 = true;
            上次交战时间 = Time.time;
        }

        if (!已交战) { 进入状态(NpcAiState.待机); return; }

        // 交战中：够得着就出手，够不着就追
        if (可出手()) { 进入攻击(); return; }
        // 【坑】以前是"走到 <= 攻击距离 就停"，而 可出手() 又要求 "<= 攻击距离" ——
// 停在边界上时浮点误差会让它判定"够不着"，于是**站着不动也永远不出手**。
// 所以接近时停得**比攻击距离近一点**，让自己舒服地在射程内。
float 停靠距离 = Mathf.Max(0.5f, 攻击距离 * 0.85f);
        if (到敌人距离 <= 停靠距离) { 进入状态(NpcAiState.待机); 朝向敌人(); return; }
        进入状态(NpcAiState.接近);
    }

    /// <summary>
    /// **清掉战斗锁定，重新开始索敌。**
    ///
    /// 玩家死亡→重生时由 <see cref="PlayerDeathSequence"/> 全场调一次。
    /// 不调的话它们会停在"待机"发呆，要等下一次 <see cref="重新索敌冷却"/> 才动，
    /// 看着就像"AI 卡死了"。
    /// </summary>
    public void 重置战斗状态()
    {
        已交战 = false;
        上次交战时间 = -999f;          // 清掉索敌冷却，重生后立刻能重新发现玩家
        if (状态 != NpcAiState.死亡) 进入状态(NpcAiState.待机);
    }

    // ---- ASCII 别名 ----
    public bool InCombat => 已交战;
    public float HostileFavorThreshold => 敌对好感阈值;
}
