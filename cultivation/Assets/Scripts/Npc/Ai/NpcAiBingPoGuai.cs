using UnityEngine;

/// <summary>
/// 冰魄怪（BingPoGuai）—— **近战普攻 + 冰弹神通**。
///
/// 一个类覆盖 4 个变体（`BingPoGuai_01 ~ 04`，共用同一份 `NpcDefinition`）。
///
/// | 招 | 动画 | 属性 | 类别 | 倍率 | 冷却 | 出手进度 | 打出去的是什么 |
/// |---|---|---|---|---|---|---|---|
/// | 普攻 | `Attack1`（1.20s） | **物理** | 普通攻击 | 1.0 | **2 秒** | **60%** | 前伸的右手（近战） |
/// | 主动神通 | `Attack2`（1.67s） | **特殊** | 普通攻击 | 2.0 | **12 秒** | **63%** | 左手射出的**冰弹** |
/// | — | `Attack3` | 不用 | | | | | |
///
/// ### 普攻：物理近战，动画 60% 处出伤
///
/// 策划原话：「普攻用前伸的右手的网格来做伤害判定，动画的 60% 处是出伤实际，给命中特效」。
/// 实现上**不做出手网格判定**（理由见 §18：网格判定等价于距离判定，
/// 而且特效必须跟出伤同一时刻）—— 直接 `出手进度 = 0.60`，
/// **出伤和命中特效都在 60% 那一刻**，命中特效沿用物理攻击的基础特效（`FX/Hit_Physical`）。
///
/// ### 冰弹（主动神通）的 5 个要素
///
/// | 要素 | 做法 |
/// |---|---|
/// | **1 出生点** | 左手骨骼末端：挂点 `Bip01 L Hand` + 一点偏移（模型里没有手指骨，只能近似） |
/// | **2 飞行路径** | **生成时朝玩家方向直线飞、匀速、不追踪**（`NpcProjectile.设置直线飞行`） |
/// | **3 命中效果** | 对玩家造成**特殊 · 普通攻击**（`DamageNature.特殊` + `AttackKind.普通攻击`） |
/// | **4 能否被阻挡** | **不和场景碰撞**（墙挡不住），只检测 `拦截层` = 图层「**拦截**」（index 8）。<br>以后技能神通 / 法宝 / 灵阵放到那一层，就能把这发冰弹打掉 |
/// | **5 消灭点** | 飞出 `消灭距离`（22 米）就自行**淡化消散** |
///
/// ### 冰属性观感
///
/// 弹道 / 枪口闪光 / 命中爆炸**全部用 QFX 的 Winter 系列**（这套包的 Winter 就是冰系配色，偏冰蓝）：
/// `VFX_Winter_Projectile_Only` + `VFX_Winter_Flash` + `VFX_Winter_Impact`。
/// 想更冷更蓝就把这三个路径换成别的（`VFX_Winter_*` 是现成的一套）。
/// </summary>
public class NpcAiBingPoGuai : NpcAiDemon
{
    [Header("冰魄怪 · 普攻（近战）")]
    [Tooltip("普攻冷却（秒）—— **策划定 2 秒一次**")]
    public float 普攻冷却 = 2f;

    [Tooltip("普攻在动画的百分之多少处【出伤 + 放命中特效】。**策划定 60%**\n\n" +
             "【为什么曾经想改】Attack1 量出来手臂是「往右前下方」而不是「往前伸」，\n" +
             "一度以为出伤点该往后挪。**但那是假象** —— 真因是 AI 在播攻击动画时\n" +
             "还每帧把根节点转回目标，把动画自带的「转体」抵消掉了，手才刺歪。\n" +
             "修了 `攻击期间锁定朝向` 之后这里保持 60%。见开发注意事项 §20。")]
    [Range(0.05f, 0.95f)]
    public float 普攻出手进度 = 0.60f;

    [Tooltip("普攻倍率")]
    public float 普攻倍率 = 1f;

    [Tooltip("普攻用的命中特效。留空 = 自动用 NpcAiBase.物理基础命中特效（FX/Hit_Physical）")]
    public string 普攻命中特效 = "";

    [Header("冰魄怪 · 冰弹（主动神通）")]
    [Tooltip("主动神通冷却（秒）—— **策划定 12 秒**")]
    public float 神通冷却 = 12f;

    [Tooltip("冰弹在动画的百分之多少处生成。**策划定 63%**")]
    [Range(0.05f, 0.95f)]
    public float 神通出手进度 = 0.63f;

    [Tooltip("冰弹倍率（策划没给数，先按和其它怪的主动神通一致取 2.0）")]
    public float 神通倍率 = 2f;

    [Header("冰弹 · 出生点与弹道")]
    [Tooltip("左手末端骨骼名（模型里没有手指骨，只有 Bip01 L Hand）")]
    public string 左手末端骨骼 = "Bip01 L Hand";

    [Tooltip("左手末端再往前一点（沿手的前方），近似「骨骼末端」")]
    public Vector3 左手末端偏移 = new Vector3(0f, 0f, 0.55f);

    [Tooltip("冰弹速度（米/秒）")]
    public float 飞弹速度 = 16f;

    [Tooltip("飞出这么远就自行淡化消散（消灭点，米）")]
    public float 消灭距离 = 22f;

    [Tooltip("弹体缩放")]
    public float 弹体缩放 = 1.1f;

    [Header("冰弹 · 冰属性特效（QFX 的 Winter 系列）")]
    [Tooltip("特效包前缀")]
    public string 包前缀 = "QFX/ProjectilesFX/VFX_Prefabs/";

    [Tooltip("纯弹道（不带飞行脚本、不带命中分支）—— 这样才能「不被场景阻挡」")]
    public string 弹道 = "Projectiles_Particles/VFX_Winter_Projectile_Only";

    [Tooltip("命中爆炸")]
    public string 命中 = "Impacts/VFX_Winter_Impact";

    [Tooltip("枪口闪光（可留空）")]
    public string 闪光 = "Flashes/VFX_Winter_Flash";

    protected override void 取默认参数()
    {
        确保攻击方式();          // ★ 先保证三条默认招式在（Awake 没跑过时也不会静默早退）
        base.取默认参数();

        // 近战站位 = 中心距。冰魄怪的爪子比白熊精的武器短，
        // 所以站得比熊近一点；数值可以在 Inspector 上按观感调（和熊一样：要"压到人身上"）
        索敌范围 = 14f;
        脱战范围 = 22f;
        攻击距离 = 2.5f;
        攻击间隔倍率 = 1.3f;
        转向速度 = 480f;
        奔跑倍率 = 1f;

        if (攻击方式 == null || 攻击方式.Length < 2) return;

        // ---- 普攻：Attack1，物理普通攻击，动画 60% 出伤 + 命中特效 ----
        var 普攻 = 攻击方式[0];
        普攻.动作名 = "Attack1";
        普攻.是施法 = false;                     // 近战，没有飞弹
        普攻.伤害属性 = DamageNature.物理;
        普攻.攻击类别 = AttackKind.普通攻击;
        普攻.技能倍率 = 普攻倍率;
        普攻.冷却 = 普攻冷却;
        普攻.出手进度 = 普攻出手进度;              // ← 出伤 + 特效都在 60% 这一刻
        普攻.命中特效路径 = 普攻命中特效;          // 留空 → 物理攻击自动用基础命中特效
        清掉飞弹配置(普攻);

        // ---- 主动神通：Attack2，特殊普通攻击的冰弹，动画 63% 生成，冷却 12 秒 ----
        var 神通 = 攻击方式[1];
        神通.动作名 = "Attack2";
        神通.是施法 = true;                      // ★ 施法 → 走飞弹
        神通.伤害属性 = DamageNature.特殊;        // 策划：特殊
        神通.攻击类别 = AttackKind.普通攻击;      // 策划：普通攻击 → 合起来就是「特殊普通攻击」
        神通.技能倍率 = 神通倍率;
        神通.冷却 = 神通冷却;
        神通.出手进度 = 神通出手进度;              // ← 63% 处生成飞弹
        神通.挂点 = 左手末端骨骼;                  // 出生点 = 左手骨骼末端
        神通.挂点偏移 = 左手末端偏移;
        神通.子弹速度 = 飞弹速度;
        神通.弹体缩放 = 弹体缩放;
        神通.命中特效缩放 = 1.3f;
        神通.最大飞行距离 = 消灭距离;              // 消灭点
        神通.闪光特效路径 = 包前缀 + 闪光;
        神通.子弹特效路径 = 包前缀 + 弹道;
        神通.命中特效路径 = 包前缀 + 命中;
        神通.拦截层 = 取拦截层();                  // 技能神通 / 法宝 / 灵阵 能拦下来

        // Attack3 不用
        攻击方式[2].动作名 = "";
    }

    /// <summary>
    /// 图层「拦截」的 mask。**场景里的墙永远拦不住冰弹**（飞弹不和场景碰撞），
    /// 只有放到这一层的东西（以后的技能神通 / 法宝 / 灵阵）能把它打掉。
    /// 图层没建出来就返回 0 = 谁都拦不住，免得 `1 &lt;&lt; -1` 溢出成一个乱七八糟的 mask。
    /// </summary>
    static LayerMask 取拦截层()
    {
        int 层 = LayerMask.NameToLayer("拦截");
        return 层 < 0 ? 0 : 1 << 层;
    }

    /// <summary>
    /// 只清**飞弹专属**的配置。注意**不能清命中特效路径**（基础命中特效也要用；
    /// 白熊精那次就是把神通刚设好的命中特效给清掉了）。
    /// </summary>
    static void 清掉飞弹配置(NpcAttackConfig 配置)
    {
        配置.子弹特效路径 = "";
        配置.闪光特效路径 = "";
    }

    /// <summary>左手末端的大致世界坐标（模型没有手指骨，用 手 + 偏移 近似）</summary>
    public Vector3 取左手末端()
    {
        var 手 = 找挂点(左手末端骨骼);
        return 手 != null ? 手.TransformPoint(左手末端偏移) : 取出膛点();
    }

    // ---- ASCII 别名 ----
    public float BasicCooldown => 普攻冷却;
    public float SkillCooldown => 神通冷却;
    public LayerMask InterceptMask => 取拦截层();
}
